# Converts a PNG/JPG/... logo into a C array plus a qrk_image definition for
# the QRKude raster renderers (Arduino, ESP-IDF, LVGL, plain C).
#
# usage: img2qrk.py logo.png -o logo.h -n logo -f RGB565 -s 32
#
# Formats (qrk_pixel_format):
#   RGB565          uint16_t per pixel, native endian      (TFT, LVGL 16-bit)
#   RGB565_SWAPPED  uint16_t per pixel, bytes swapped       (raw SPI buffers)
#   RGBA8888        bytes R,G,B,A (keeps transparency)
#   BGRA8888        bytes B,G,R,A (LVGL 9 ARGB8888)
#   RGB888          bytes R,G,B
#   GRAY8           one byte of luminance per pixel
#   MONO            1 bit per pixel, MSB first, 1 = dark   (OLEDs, AVR)
#
# Formats without alpha are composited over --background (default white).
# Requires Pillow (pip install pillow).
import argparse
import os
import re
import sys

try:
    from PIL import Image
except ImportError:  # pragma: no cover
    sys.exit("img2qrk.py needs Pillow: pip install pillow")

FORMATS = ("RGB565", "RGB565_SWAPPED", "RGBA8888", "BGRA8888", "RGB888", "GRAY8", "MONO")


def parse_color(text):
    m = re.fullmatch(r"#?([0-9a-fA-F]{6})", text)
    if not m:
        raise argparse.ArgumentTypeError("expected a color like #ffffff")
    v = int(m.group(1), 16)
    return (v >> 16) & 255, (v >> 8) & 255, v & 255


def c_identifier(text):
    name = re.sub(r"[^0-9a-zA-Z_]", "_", text)
    return name if name and not name[0].isdigit() else "img_" + name


def load(path, size, background):
    img = Image.open(path).convert("RGBA")
    if size:
        scale = size / max(img.width, img.height)
        w = max(1, round(img.width * scale))
        h = max(1, round(img.height * scale))
        img = img.resize((w, h), Image.LANCZOS)
    flat = Image.new("RGBA", img.size, background + (255,))
    flat.alpha_composite(img)
    return img, flat.convert("RGB")


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def pixels(img, channels):
    """Pixel tuples of an RGB/RGBA image (or ints for "L") via tobytes()."""
    raw = img.tobytes()
    if channels == 1:
        return list(raw)
    return [tuple(raw[i:i + channels]) for i in range(0, len(raw), channels)]


def convert(img, flat, fmt, threshold):
    """Returns (C element type, list of values, bytes)."""
    w, h = img.size
    if fmt in ("RGB565", "RGB565_SWAPPED"):
        vals = []
        for r, g, b in pixels(flat, 3):
            v = rgb565(r, g, b)
            if fmt == "RGB565_SWAPPED":
                v = ((v >> 8) | (v << 8)) & 0xFFFF
            vals.append(v)
        return "uint16_t", vals, 2 * len(vals)
    if fmt == "RGBA8888":
        vals = list(img.tobytes())
    elif fmt == "BGRA8888":
        vals = [c for r, g, b, a in pixels(img, 4) for c in (b, g, r, a)]
    elif fmt == "RGB888":
        vals = list(flat.tobytes())
    elif fmt == "GRAY8":
        vals = pixels(flat.convert("L"), 1)
    else:  # MONO: 1 = dark
        gray = pixels(flat.convert("L"), 1)
        stride = (w + 7) // 8
        vals = [0] * (stride * h)
        for y in range(h):
            for x in range(w):
                if gray[y * w + x] < threshold:
                    vals[y * stride + x // 8] |= 0x80 >> (x % 8)
    return "uint8_t", vals, len(vals)


def emit(out, name, src, img, fmt, ctype, vals, nbytes, comments=()):
    w, h = img.size
    per_line = 12 if ctype == "uint16_t" else 16
    fmt_val = "0x{:04x}" if ctype == "uint16_t" else "0x{:02x}"
    guard = c_identifier(name).upper() + "_QRK_IMAGE_H"
    lines = ["/*"] + [f" * {c}" for c in comments] + ([" *"] if comments else []) + [
        f" * Generated by img2qrk.py from {os.path.basename(src)}: {w}x{h} {fmt}, {nbytes} bytes.",
        " * Regenerate: python3 img2qrk.py "
        f"{os.path.basename(src)} -n {name} -f {fmt} -s {max(w, h)} -o {os.path.basename(out) if out else '-'}",
        " *",
        " * The array is const: it stays in flash on ESP32, RP2040, SAMD and STM32.",
        " * On AVR and ESP8266 const data is copied to RAM (the core reads the",
        " * pixels with plain loads, so PROGMEM cannot be used): keep logos small,",
        " * MONO is 8x smaller than RGB565. */",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "#include <stdint.h>",
        "",
        "#ifndef QRKUDE_H",
        '#error "include QRKude.h (Arduino) or qrkude.h before this file"',
        "#endif",
        "",
        f"static const {ctype} {name}_pixels[{len(vals)}] = {{",
    ]
    for i in range(0, len(vals), per_line):
        chunk = ", ".join(fmt_val.format(v) for v in vals[i:i + per_line])
        lines.append(f"    {chunk},")
    lines += [
        "};",
        "",
        f"static const qrk_image {name} = {{{w}, {h}, QRK_PIXEL_{fmt}, {name}_pixels, 0}};",
        "",
        f"#endif /* {guard} */",
        "",
    ]
    text = "\n".join(lines)
    if out:
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    else:
        sys.stdout.write(text)


def main(argv=None):
    p = argparse.ArgumentParser(description="Convert an image into a qrk_image C array.")
    p.add_argument("input", help="image file (PNG, JPG, BMP, GIF...)")
    p.add_argument("-o", "--output", help="header to write (default: stdout)")
    p.add_argument("-n", "--name", help="C identifier (default: from the file name)")
    p.add_argument("-f", "--format", default="RGB565", type=str.upper, choices=FORMATS)
    p.add_argument("-s", "--size", type=int, default=0,
                   help="resize so that the longest side is SIZE px (default: keep)")
    p.add_argument("-b", "--background", type=parse_color, default=(255, 255, 255),
                   help="color under transparent pixels for formats without alpha (#rrggbb)")
    p.add_argument("-t", "--threshold", type=int, default=128,
                   help="MONO: luminance below this is dark (default 128)")
    p.add_argument("-c", "--comment", action="append", default=[],
                   help="extra line for the header comment (repeatable), e.g. a copyright")
    args = p.parse_args(argv)

    name = c_identifier(args.name or os.path.splitext(os.path.basename(args.input))[0])
    img, flat = load(args.input, args.size, args.background)
    ctype, vals, nbytes = convert(img, flat, args.format, args.threshold)
    emit(args.output, name, args.input, img, args.format, ctype, vals, nbytes, args.comment)
    if args.output:
        print(f"{args.output}: {name} {img.width}x{img.height} {args.format}, {nbytes} bytes",
              file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
